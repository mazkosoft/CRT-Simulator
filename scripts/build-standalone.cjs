// Reproducible single-file release. No bundler or package installation required.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = name => fs.readFileSync(path.join(root, name), 'utf8');
const escapeHtml = text => text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

function buildStandalone() {
  let html = read('index.html');
  const demo = 'data:image/png;base64,' + fs.readFileSync(path.join(root, 'assets/demo-desktop.png')).toString('base64');
  html = html.replace(/<link rel="stylesheet" href="([^"]+)"\s*\/>/g, (_, name) => {
    const css = read(name.split('?')[0]);
    if (/<\/style/i.test(css) || /url\(/i.test(css)) throw new Error(`Review CSS asset embedding: ${name}`);
    return `<style data-source="${name.split('?')[0]}">\n${css}\n</style>`;
  });
  html = html.replace(/<script src="([^"]+)"><\/script>/g, (_, name) => {
    let source = read(name);
    if (name === 'js/crt.js') {
      const imageUrl = 'new URL("assets/demo-desktop.png", document.baseURI).href';
      if (!source.includes(imageUrl)) throw new Error('Default-image loader changed; update standalone builder');
      source = source.replace(imageUrl, JSON.stringify(demo));
    }
    // HTML raw-text elements must not contain literal closing-script sequences.
    source = source.replace(/<\/script/gi, '<\\/script');
    // The AAC worker payload contains binary control characters. JSON quoting
    // protects them from HTML parser normalization while retaining global exports.
    if (name === 'vendor/mediabunny-aac-encoder.min.js') source = `(0, eval)(${JSON.stringify(source + '\nglobalThis.MediabunnyAacEncoder = MediabunnyAacEncoder;').replace(/</g, '\\u003c')});`;
    return `<script data-source="${name}">\n${source}\n</script>`;
  });
  const notices = ['LICENSE', 'THIRD_PARTY_NOTICES.md', 'vendor/MEDIABUNNY-LICENSE.txt', 'vendor/AAC-ENCODER-LICENSE.txt', 'vendor/FFMPEG-LGPL-2.1.txt', 'vendor/AAC-ENCODER-README.md']
    .map(name => `${name}\n${'='.repeat(name.length)}\n${read(name)}`).join('\n\n');
  const legal = `<details id="bundledLicenses"><summary data-i18n-zh="完整许可证与第三方声明" data-i18n-en="Full licenses and third-party notices">完整许可证与第三方声明</summary><pre style="max-height:240px;overflow:auto;white-space:pre-wrap;overflow-wrap:anywhere;font-size:12px">${escapeHtml(notices)}</pre></details>`;
  const aboutEnd = html.indexOf('</details>', html.indexOf('id="aboutGroup"'));
  if (aboutEnd < 0) throw new Error('About group not found');
  html = html.slice(0, aboutEnd) + legal + '\n' + html.slice(aboutEnd);
  return html.replace('<!DOCTYPE html>', '<!DOCTYPE html>\n<!-- Generated by scripts/build-standalone.cjs. Edit split source, then regenerate. -->');
}

if (require.main === module) {
  const destination = path.join(root, 'dist', 'crt-simulator-standalone.html');
  fs.mkdirSync(path.dirname(destination), { recursive: true });
  fs.writeFileSync(destination, buildStandalone());
  console.log(`Generated ${destination}`);
}
module.exports = { buildStandalone };
